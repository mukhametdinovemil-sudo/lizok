const tidy = t => { ['hint', 'explain'].forEach(k => { if (t[k]) t[k] = U.dots(t[k]); }); return t; };
const T = {
  num(q, answer, o = {}) { return tidy(Object.assign({ type: 'num', q, answer }, o)); },
  rem(q, qv, rv, o = {}) { return tidy(Object.assign({ type: 'rem', q, answer: { q: qv, r: rv } }, o)); },
  choice(q, answer, options, o = {}) {
    return tidy(Object.assign({ type: 'choice', q, answer: String(answer), options: U.shuffle(options.map(String)) }, o));
  },
};
const ex = s => `<div class="expr">${s}</div>`;
const word = s => `<p class="word">${s}</p>`;
const X = '<i class="x">x</i>';
const BOX = '<span class="miss">?</span>';
const zerosWord = z => ({ 10: 'один нуль', 100: 'два нуля', 1000: 'три нуля' }[z]);
// записать цифры с пробелами между классами, где одна цифра — «?»
function groupDigits(arr) {
  const s = arr.slice();
  if (s.length < 4) return s.join('');
  let out = '';
  for (let i = 0; i < s.length; i++) {
    out += s[i];
    const left = s.length - 1 - i;
    if (left > 0 && left % 3 === 0) out += ' ';
  }
  return out;
}
function firstPartial(D, d) {
  const dg = String(D).split('').map(Number);
  let i = 0, cur = dg[0];
  while (cur < d && i < dg.length - 1) { i++; cur = cur * 10 + dg[i]; }
  return { cur, len: dg.length - i, rank: dg.length - 1 - i };
}
function mulTask(a, b) {
  return T.num(ex(`${U.fmt(a)} · ${b} = ?`), a * b, {
    hint: `Начни с единиц: ${a % 10} · ${b} = ${(a % 10) * b}. Не забывай прибавлять то, что запомнила.`,
    explain: 'Умножаем столбиком справа налево: единицы, десятки, сотни… Если получилось двузначное число — пишем единицы, а десятки запоминаем и прибавляем к следующему разряду.',
    sol: { kind: 'mul', a, b },
    meta: { expr: `${a}*${b}` },
  });
}
function divTask(D, d, extra = {}) {
  const fp = firstPartial(D, d);
  return T.num(ex(`${U.fmt(D)} : ${d} = ?`), D / d, Object.assign({
    hint: `Первое неполное делимое — ${fp.cur} ${U.RANK_SHORT[fp.rank]}. Значит, в частном будет ${fp.len} ${U.plural(fp.len, 'цифра', 'цифры', 'цифр')}.`,
    explain: 'Делим по шагам: делю → умножаю → вычитаю → сравниваю (остаток меньше делителя) → сношу следующую цифру.',
    sol: { kind: 'div', D, d },
    meta: { expr: `${D}/${d}` },
  }, extra));
}

