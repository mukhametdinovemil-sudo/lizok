function addTask(a, b, o = {}) {
  return T.num(ex(`${U.fmt(a)} + ${U.fmt(b)} = ?`), a + b, Object.assign({
    hint: `Начни с единиц: ${a % 10} + ${b % 10} = ${(a % 10) + (b % 10)}. Если получилось 10 или больше — 1 запоминай.`,
    explain: 'Складываем столбиком справа налево. Если в разряде получилось 10 или больше — пишем единицы, а 1 переносим в следующий разряд.',
    sol: { kind: 'add', a, b },
    meta: { expr: `${a}+${b}` },
  }, o));
}
function subTask(a, b, o = {}) {
  return T.num(ex(`${U.fmt(a)} − ${U.fmt(b)} = ?`), a - b, Object.assign({
    hint: 'Если верхняя цифра меньше нижней — занимай 1 у соседнего разряда. Нули по дороге превращаются в 9.',
    explain: `Вычитаем столбиком справа налево. Проверка сложением: ${U.fmt(a - b)} + ${U.fmt(b)} = ${U.fmt(a)}.`,
    sol: { kind: 'sub', a, b },
    meta: { expr: `${a}-${b}` },
  }, o));
}
// число с нулями внутри для «вычитания через нули»: 800 304, 70 005, 100 000
function zeroish(L) {
  const s = [U.rnd(1, 9)];
  for (let i = 1; i < L; i++) s.push(Math.random() < 0.6 ? 0 : U.rnd(1, 9));
  if (s.slice(1).every(d => d !== 0)) s[U.rnd(1, L - 1)] = 0;
  return Number(s.join(''));
}

