T.pair = (q, a, b, labels, o = {}) => tidy(Object.assign({ type: 'pair', q, answer: { q: a, r: b }, labels }, o));

const UNITS = {
  len: { 'мм': 1, 'см': 10, 'дм': 100, 'м': 1000, 'км': 1000000 },
  mass: { 'г': 1, 'кг': 1000, 'ц': 100000, 'т': 1000000 },
  area: { 'мм²': 1, 'см²': 100, 'дм²': 10000, 'м²': 1000000, 'км²': 1e12 },
};
// пары [крупная, мелкая, во сколько раз]
function unitPairs(kind, maxF, neighbors) {
  const u = UNITS[kind], names = Object.keys(u), out = [];
  for (let i = 0; i < names.length; i++) {
    for (let j = 0; j < i; j++) {
      const f = u[names[i]] / u[names[j]];
      if (f <= maxF && (!neighbors || i - j === 1)) out.push([names[i], names[j], f]);
    }
  }
  return out;
}
