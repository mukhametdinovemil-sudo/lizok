function genUnitChoice(list, opts, what) {
  const [name, v, u] = U.pick(list);
  return T.choice(word(`${name} — ${v} … Какая единица подходит?`), u, opts, {
    hint: `Представь себе этот предмет. Это мелкая или большая ${what}?`,
    explain: `${name} — ${v} ${u}.`,
    meta: { choiceRight: u },
  });
}

