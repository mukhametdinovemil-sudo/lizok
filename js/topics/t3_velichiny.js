const rule = (big, small, f) => `1 ${big} = ${U.fmt(f)} ${small}`;

// ── универсальные генераторы перевода единиц ──
function genBigToSmall(pairs) {
  const [big, small, f] = U.pick(pairs);
  const v = U.rnd(2, Math.max(2, Math.min(99, Math.floor(9999999 / f))));
  return T.num(ex(`${v} ${big} = ? ${small}`), v * f, {
    unit: small,
    hint: `${rule(big, small, f)}. Крупные единицы переводим в мелкие — умножаем.`,
    explain: `${rule(big, small, f)}, поэтому ${v} ${big} = ${v} · ${U.fmt(f)} = ${U.fmt(v * f)} ${small}.`,
    meta: { expr: `${v}*${f}` },
  });
}
function genSmallToBig(pairs) {
  const [big, small, f] = U.pick(pairs);
  const k = U.rnd(2, Math.max(2, Math.min(99, Math.floor(9999999 / f)))), N = k * f;
  return T.num(ex(`${U.fmt(N)} ${small} = ? ${big}`), k, {
    unit: big,
    hint: `${rule(big, small, f)}. Мелкие единицы переводим в крупные — делим.`,
    explain: `${rule(big, small, f)}, поэтому ${U.fmt(N)} ${small} = ${U.fmt(N)} : ${U.fmt(f)} = ${k} ${big}.`,
    meta: { expr: `${N}/${f}` },
  });
}
function genCompound(pairs, maxA = 20) {
  const [big, small, f] = U.pick(pairs);
  const a = U.rnd(1, maxA), b = U.rnd(1, f - 1);
  return T.num(ex(`${a} ${big} ${b} ${small} = ? ${small}`), a * f + b, {
    unit: small,
    hint: `Сначала переведи ${a} ${big} в ${small}, потом прибавь ${b} ${small}.`,
    explain: `${a} ${big} = ${U.fmt(a * f)} ${small}. ${U.fmt(a * f)} + ${b} = ${U.fmt(a * f + b)} ${small}.${f >= 100 && b < f / 10 ? ' Обрати внимание на нули!' : ''}`,
    meta: { expr: `${a}*${f}+${b}` },
  });
}
function genSplit(pairs, maxA = 20) {
  const [big, small, f] = U.pick(pairs);
  const a = U.rnd(1, maxA), b = U.rnd(1, f - 1), N = a * f + b;
  return T.pair(ex(`${U.fmt(N)} ${small} = ${BOX} ${big} ${BOX} ${small}`), a, b, [big, small], {
    hint: `${rule(big, small, f)}. Сколько целых ${big} помещается в ${U.fmt(N)} ${small}? Что останется?`,
    explain: `${U.fmt(N)} : ${U.fmt(f)} = ${a} (ост. ${b}). Значит, ${U.fmt(N)} ${small} = ${a} ${big} ${b} ${small}.`,
    meta: { pairExpr: `[Math.floor(${N}/${f}), ${N}%${f}]` },
  });
}
function genCompare(pairs) {
  const [big, small, f] = U.pick(pairs);
  const a = U.rnd(1, 9), base = a * f;
  const kind = U.rnd(1, 3);
  const b = kind === 1 ? base : kind === 2 ? base + U.rnd(1, Math.max(1, Math.floor(f / 2))) : base - U.rnd(1, Math.max(1, Math.floor(f / 2)));
  const sign = base > b ? '>' : base < b ? '<' : '=';
  return T.choice(ex(`${a} ${big} ${BOX} ${U.fmt(b)} ${small}`) + '<p class="sub">Какой знак поставить?</p>', sign, ['<', '>', '='], {
    hint: `Переведи ${a} ${big} в ${small} и сравни числа.`,
    explain: `${a} ${big} = ${U.fmt(base)} ${small}. ${U.fmt(base)} ${sign} ${U.fmt(b)}, поэтому ${a} ${big} ${sign} ${U.fmt(b)} ${small}.`,
    meta: { choiceExpr: `(${base}>${b})?'>':(${base}<${b})?'<':'='` },
  });
}

