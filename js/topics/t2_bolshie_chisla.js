const POS_NAMES = ['единиц', 'десятков', 'сотен', 'единиц тысяч', 'десятков тысяч', 'сотен тысяч', 'единиц миллионов', 'десятков миллионов', 'сотен миллионов'];
const N_ZEROS = z => ({ 1: 'один нуль', 2: 'два нуля', 3: 'три нуля', 4: 'четыре нуля', 5: 'пять нулей', 6: 'шесть нулей' }[z]);
const nzCount = n => String(n).split('0').length - 1;
const N_SIGN = (a, b) => (a > b ? '>' : a < b ? '<' : '=');
// «единицы» в записи «t тыс. u ед.»: чаще с нулями внутри, чтобы была ловушка
const rndUnits = () => U.pick([U.rnd(1, 9), U.rnd(1, 9) * 10, U.rnd(1, 9) * 100, U.rnd(101, 999), U.rnd(11, 99)]);

function nBigCompare() {
  const L = U.rnd(4, 7);
  const a = U.digits(L);
  let b;
  if (Math.random() < 0.2) b = a;
  else {
    const s = String(a).split(''), k = U.rnd(0, L - 1);
    let d;
    do { d = U.rnd(k === 0 ? 1 : 0, 9); } while (d === Number(s[k]));
    s[k] = d; b = Number(s.join(''));
  }
  const sg = N_SIGN(a, b);
  const first = String(a).split('').findIndex((c, i) => c !== String(b)[i]);
  return T.choice(ex(`${U.fmt(a)} ${BOX} ${U.fmt(b)}`) + '<p class="sub">Какой знак поставить?</p>', sg, ['<', '>', '='], {
    hint: 'Цифр поровну. Сравнивай слева направо: сначала самые большие разряды.',
    explain: sg === '=' ? 'Числа одинаковые.' : `Цифры сначала совпадают, а в разряде «${POS_NAMES[L - 1 - first]}» разные: ${String(a)[first]} и ${String(b)[first]}. Значит, ${U.fmt(a)} ${sg} ${U.fmt(b)}.`,
    meta: { choiceExpr: `(${a}>${b})?'>':(${a}<${b})?'<':'='` },
  });
}

