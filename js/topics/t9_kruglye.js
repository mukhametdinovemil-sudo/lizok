const zw = z => ({ 1: 'один нуль', 2: 'два нуля', 3: 'три нуля', 4: 'четыре нуля', 5: 'пять нулей', 6: 'шесть нулей', 7: 'семь нулей' }[z]);
const zc = n => { let z = 0; while (n > 0 && n % 10 === 0) { n /= 10; z++; } return z; };
const strip = n => n / 10 ** zc(n);

function roundMulTask(a, b) {
  const sa = strip(a), sb = strip(b), z = zc(a) + zc(b);
  return T.num(ex(`${U.fmt(a)} · ${U.fmt(b)} = ?`), a * b, {
    hint: `Умножь числа без нулей: ${sa} · ${sb}. Потом припиши все нули: их ${z}.`,
    explain: `${sa} · ${sb} = ${U.fmt(sa * sb)}, приписываем ${zw(z)}: ${U.fmt(a * b)}.${zc(sa * sb) ? ' Заметь: в ответе нулей больше, потому что они появились и при умножении!' : ''}`,
    sol: sa > 9 && sb < 10 ? { kind: 'mul', a: sa, b: sb } : undefined,
    meta: { expr: `${a}*${b}` },
  });
}
function mul2Task(a, b, o = {}) {
  return T.num(ex(`${U.fmt(a)} · ${b} = ?`), a * b, Object.assign({
    hint: `Сначала ${U.fmt(a)} · ${b % 10}, потом ${U.fmt(a)} · ${Math.floor(b / 10)} (это десятки — пиши со сдвигом), потом сложи.`,
    explain: `${U.fmt(a)} · ${b % 10} = ${U.fmt(a * (b % 10))}, ${U.fmt(a)} · ${Math.floor(b / 10) * 10} = ${U.fmt(a * Math.floor(b / 10) * 10)}. Сумма: ${U.fmt(a * b)}.`,
    sol: { kind: 'mul2', a, b },
    meta: { expr: `${a}*${b}` },
  }, o));
}
